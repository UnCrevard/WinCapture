void icons_init(void)
{
    static unsigned char full[ICN * ICN];
    int n = BTN_H - 2 * S(2);
    if (n < 8) n = 8;
    g_icoPx = n;
    icons_free();
    for (int k = 0; k < ICO_N; k++) {
        int o = 0;
        for (int i = 0; i + 1 < g_rleLen[k]; i += 2) {
            int c = g_rleData[k][i + 1];
            while (c-- > 0 && o < ICN * ICN) full[o++] = g_rleData[k][i];
        }
        while (o < ICN * ICN) full[o++] = 0;
        g_icoMask[k] = (unsigned char *)malloc((size_t)n * n);
        if (!g_icoMask[k]) continue;
        for (int y = 0; y < n; y++)
            for (int x = 0; x < n; x++) {
                int x0 = x * ICN / n, x1 = (x + 1) * ICN / n;
                int y0 = y * ICN / n, y1 = (y + 1) * ICN / n;
                int sum = 0, sx, sy;
                if (x1 <= x0) x1 = x0 + 1;
                if (y1 <= y0) y1 = y0 + 1;
                for (sy = y0; sy < y1; sy++)
                    for (sx = x0; sx < x1; sx++) sum += full[sy * ICN + sx];
                g_icoMask[k][y * n + x] = (unsigned char)(sum / ((x1 - x0) * (y1 - y0)));
            }
    }
}

